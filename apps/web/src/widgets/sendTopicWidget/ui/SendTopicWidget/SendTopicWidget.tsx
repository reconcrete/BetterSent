import { type FC, useState, useCallback, useRef } from "react";
import { Info } from "lucide-react";

import { Textarea } from "~/shared/ui";

import { SendContent } from "~/features/sendContent";
import { ChooseDevice } from "~/features/chooseDevice";
import { useSubscriptionStatus } from "~/entities/billing";

import { UpgradePrompt } from "~/widgets/upgradePrompt";

export const SendTopicWidget: FC = () => {
  const { data: status } = useSubscriptionStatus();
  const [topic, setTopic] = useState("");
  const [kindleId, setKindleId] = useState<string | undefined>(undefined);
  const submitRef = useRef<(() => void) | null>(null);

  const handleSuccess = () => setTopic("");
  const handleKindleChange = useCallback((id: string | undefined) => setKindleId(id), []);

  if (status?.plan === "free") {
    return (
      <UpgradePrompt
        title="Unlock Topic to Kindle"
        description="Enter any topic or question and get a mini book generated by AI, sent straight to your Kindle."
      />
    );
  }

  return (
    <div className="flex flex-col gap-5">
      <div className="flex items-center gap-1.5 justify-center">
        <Info className="size-[15px] shrink-0 text-muted-foreground" />
        <p className="text-sm text-muted-foreground">
          Enter a topic or question to generate a mini book for your Kindle
        </p>
      </div>

      <div className="flex flex-col gap-3">
        <Textarea
          placeholder="Enter a topic or question, e.g. 'How stablecoins work and why USDT is priced at exactly 1 USD'"
          value={topic}
          onChange={(e) => setTopic(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) submitRef.current?.();
          }}
        />

        <ChooseDevice value={kindleId} onChange={handleKindleChange} />
      </div>

      <SendContent type="topic" content={topic} kindleEmailId={kindleId} onSuccess={handleSuccess} submitRef={submitRef} />
    </div>
  );
};
